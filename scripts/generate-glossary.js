const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");
const glossaryJsonPath = path.join(rootDir, "src/lib/glossary.json");
const glossaryMdxPath = path.join(
  rootDir,
  "docs/protocol/reference/zero-knowledge-glossary.mdx",
);

function loadGlossaryTerms() {
  const raw = fs.readFileSync(glossaryJsonPath, "utf8");
  const data = JSON.parse(raw);

  if (!data || !Array.isArray(data.terms)) {
    throw new Error(
      'Invalid glossary JSON: expected a top-level "terms" array.',
    );
  }

  return [...data.terms]
    .filter(
      (term) =>
        term &&
        typeof term.term === "string" &&
        typeof term.definition === "string",
    )
    .sort((a, b) => a.term.localeCompare(b.term));
}

function buildGlossaryMdx(terms) {
  const lines = [
    "---",
    "title: Glossary",
    "description: Definitions of Linea, Lineth, and zero-knowledge terms used across docs.linea.build.",
    "sidebar_position: 8",
    "displayed_sidebar: protocolSidebar",
    "---",
    "",
    "This glossary is open source and consistently being updated. If you'd like a term to be",
    "added or corrected, add it to `src/lib/glossary.json` in alphabetical order and open a",
    "pull request (see [CONTRIBUTING.md](https://github.com/Consensys/doc.linea/blob/main/CONTRIBUTING.md#contributing-to-the-glossary)),",
    "or [create an issue](https://github.com/Consensys/doc.linea/issues) and we'll add it.",
    "",
    "{/* AUTO-GENERATED by scripts/generate-glossary.js. */}",
    "{/* Edit src/lib/glossary.json and run npm run glossary:generate. */}",
    "",
  ];

  terms.forEach(({ term, definition }) => {
    lines.push(`### ${term}`);
    lines.push("");
    lines.push(definition.trim());
    lines.push("");
  });

  return `${lines.join("\n")}\n`;
}

function main() {
  const terms = loadGlossaryTerms();
  const mdx = buildGlossaryMdx(terms);
  fs.writeFileSync(glossaryMdxPath, mdx, "utf8");
  console.log(
    `Generated ${path.relative(rootDir, glossaryMdxPath)} from ${path.relative(rootDir, glossaryJsonPath)} (${terms.length} terms).`,
  );
}

try {
  main();
} catch (err) {
  console.error(err);
  process.exit(1);
}
